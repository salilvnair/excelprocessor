package com.github.salilvnair.excelprocessor.maven;

import com.github.salilvnair.excelprocessor.v2.outline.ColumnOutline;
import com.github.salilvnair.excelprocessor.v2.outline.ColumnType;
import com.github.salilvnair.excelprocessor.v2.outline.SheetOutline;

import javax.lang.model.SourceVersion;
import java.util.*;

/**
 * Turns a {@link SheetOutline} into the source of an annotated {@code @Sheet} class: one
 * {@code @Cell} field per header, typed from the sampled values, with {@code column} set for
 * repeated headers.
 */
public final class SheetSourceGenerator {
    private SheetSourceGenerator() {}

    /** {@code "order lines 2024"} becomes {@code OrderLines2024Sheet}. */
    public static String className(String sheetName) {
        String name = pascal(sheetName);
        if (name.isEmpty() || !Character.isJavaIdentifierStart(name.charAt(0))) {
            name = "S" + name;
        }
        return name.endsWith("Sheet") ? name : name + "Sheet";
    }

    /** {@code "Order Id"} becomes {@code orderId}; keywords and clashes get a suffix. */
    public static String fieldName(String header, Set<String> used) {
        String pascal = pascal(header);
        String name = pascal.isEmpty() ? "column" : Character.toLowerCase(pascal.charAt(0)) + pascal.substring(1);
        if (!Character.isJavaIdentifierStart(name.charAt(0))) {
            name = "_" + name;
        }
        if (SourceVersion.isKeyword(name)) {
            name = name + "Value";
        }
        String unique = name;
        for (int i = 2; !used.add(unique); i++) {
            unique = name + i;
        }
        return unique;
    }

    private static String pascal(String text) {
        StringBuilder out = new StringBuilder();
        boolean upper = true;
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            if (Character.isLetterOrDigit(c) && c < 128) {
                out.append(upper ? Character.toUpperCase(c) : c);
                upper = false;
            }
            else if (c == '#') {
                out.append("No");
                upper = true;
            }
            else {
                upper = true;
            }
        }
        return out.toString();
    }

    /**
     * @param sourceFile shown in the header comment, may be null
     * @param lombok     use Lombok {@code @Getter}/{@code @Setter} instead of writing accessors
     */
    public static String generate(SheetOutline sheet, String packageName, String className, String sourceFile, boolean lombok) {
        List<ColumnOutline> columns = sheet.columns();
        Map<String, Integer> headerCounts = new HashMap<>();
        for (ColumnOutline column : columns) {
            headerCounts.merge(column.header(), 1, Integer::sum);
        }
        boolean duplicates = headerCounts.values().stream().anyMatch(n -> n > 1);
        Set<String> imports = new TreeSet<>();
        imports.add("com.github.salilvnair.excelprocessor.v2.annotation.Cell");
        imports.add("com.github.salilvnair.excelprocessor.v2.annotation.Sheet");
        imports.add("com.github.salilvnair.excelprocessor.v2.sheet.BaseSheet");
        if (lombok) {
            imports.add("lombok.Getter");
            imports.add("lombok.Setter");
        }
        Set<String> usedNames = new HashSet<>(Arrays.asList("row", "rowIndex", "column", "columnIndex", "cells", "sheetHeaders"));
        List<String[]> fields = new ArrayList<>();
        for (ColumnOutline column : columns) {
            Class<?> type = column.type() == ColumnType.BLANK ? String.class : column.type().javaType();
            if (!type.getPackageName().equals("java.lang")) {
                imports.add(type.getName());
            }
            String annotation = headerCounts.get(column.header()) > 1
                    ? "@Cell(value = \"" + escape(column.header()) + "\", column = \"" + column.column() + "\")"
                    : "@Cell(\"" + escape(column.header()) + "\")";
            fields.add(new String[] {annotation, type.getSimpleName(), fieldName(column.header(), usedNames), column.type().name()});
        }

        StringBuilder src = new StringBuilder();
        src.append("// Generated by excelprocessor-maven-plugin");
        if (sourceFile != null) {
            src.append(" from ").append(sourceFile).append(", sheet \"").append(sheet.name()).append('"');
        }
        src.append(". Do not edit: changes are overwritten.\n");
        if (packageName != null && !packageName.isEmpty()) {
            src.append("package ").append(packageName).append(";\n\n");
        }
        for (String type : imports) {
            src.append("import ").append(type).append(";\n");
        }
        src.append('\n');
        if (lombok) {
            src.append("@Getter\n@Setter\n");
        }
        src.append("@Sheet(value = \"").append(escape(sheet.name())).append('"');
        if (sheet.headerRow() > 1) {
            src.append(", headerRowAt = ").append(sheet.headerRow());
        }
        if (!columns.isEmpty() && !"A".equals(columns.get(0).column())) {
            src.append(", headerColumnAt = \"").append(columns.get(0).column()).append('"');
        }
        if (duplicates) {
            src.append(", duplicateHeaders = true");
        }
        src.append(")\n");
        src.append("public class ").append(className).append(" extends BaseSheet {\n");
        for (String[] field : fields) {
            src.append("\n    /** inferred: ").append(field[3]).append(" */\n");
            src.append("    ").append(field[0]).append('\n');
            src.append("    private ").append(field[1]).append(' ').append(field[2]).append(";\n");
        }
        if (!lombok) {
            for (String[] field : fields) {
                String property = Character.toUpperCase(field[2].charAt(0)) + field[2].substring(1);
                src.append("\n    public ").append(field[1]).append(" get").append(property).append("() {\n");
                src.append("        return ").append(field[2]).append(";\n    }\n");
                src.append("\n    public void set").append(property).append('(').append(field[1]).append(' ').append(field[2]).append(") {\n");
                src.append("        this.").append(field[2]).append(" = ").append(field[2]).append(";\n    }\n");
            }
        }
        src.append("}\n");
        return src.toString();
    }

    private static String escape(String text) {
        StringBuilder out = new StringBuilder();
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            if (c == '"' || c == '\\') {
                out.append('\\').append(c);
            }
            else if (c < 0x20 || c > 0x7e) {
                out.append(String.format("\\u%04x", (int) c));
            }
            else {
                out.append(c);
            }
        }
        return out.toString();
    }
}
